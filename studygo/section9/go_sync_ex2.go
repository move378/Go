// 고루틴 동기화 고급(2 WaitGroup - add/done/Wait 카운팅을 이용한 실행흐름)
package main

import (
	"fmt"
	"sync"
)

func main() {
	// ============================================
	// 🎯 WaitGroup: 고루틴 완료 대기 전용 도구
	// ============================================
	// Mutex와 달리 "보호"가 아닌 "대기"가 목적
	// 내부적으로 카운터 + 세마포어로 구현됨

	wg := new(sync.WaitGroup) // 또는 var wg sync.WaitGroup
	// 포인터든 값이든 상관없지만 복사하면 안 됨!

	// ============================================
	// 🚀 100개의 고루틴 생성
	// ============================================
	for i := 0; i < 100; i++ {

		// 📍 STEP 1: 카운터 증가 (메인 스레드에서)
		wg.Add(1) // ⚠️ 중요: 고루틴 시작 **전에** Add 호출!
		// 내부 카운터: 0 → 1 → 2 → ... → 100
		// "100명이 탈 거예요"라고 미리 알림

		// 📍 STEP 2: 고루틴 실행
		go func(n int) { // n: 고루틴 번호 (0~99)
			// 익명 함수 + 즉시 실행

			// 📍 작업 수행
			fmt.Println("WaitGroup : ", n)
			// 💡 출력 순서는 보장 안 됨!
			// 여러 고루틴이 동시 실행되기 때문
			// 결과: 무작위 순서로 0~99 출력

			// 📍 STEP 3: 작업 완료 신호
			wg.Done() // ⚠️ 반드시 호출해야 함!
			// 내부 카운터 -1
			// 카운터가 0이 되면 Wait()가 해제됨
			// wg.Add(-1)과 동일

		}(i) // i를 n으로 전달 (클로저 문제 방지)
		// 만약 (i) 없으면 모든 고루틴이 같은 i 참조
	}

	// ============================================
	// ⏰ 모든 고루틴이 끝날 때까지 대기
	// ============================================
	// Add == Done 횟수가 같아야 정상 동작!
	// Add(100) vs Done() 100번 호출

	wg.Wait() // 🛑 블로킹: 카운터가 0이 될 때까지 대기
	// 카운터 > 0: 계속 대기 (CPU는 쉼)
	// 카운터 = 0: 즉시 반환
	// ⚠️ 음수가 되면 panic 발생!

	fmt.Println("WaitGroup End!")
	// 이 시점에는 100개 고루틴이 모두 종료됨
	// time.Sleep 없이도 안전!
}
