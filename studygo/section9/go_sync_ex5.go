// ============================================
// 🎯 고루틴 동기화 고급 - 원자성(Atomicity)
// ============================================
// 주제: 데이터 레이스를 방지하고 정확한 연산을 보장하는 방법
//
// 배경 지식:
// - 쓰레드(Thread): OS가 관리하는 실행 단위
// - 프로세스(Process): 독립된 메모리 공간을 가진 프로그램
// - 고루틴(Goroutine): Go 런타임이 관리하는 경량 쓰레드
//
// 생명주기:
// 프로세스 생성 → 쓰레드 생성 → 고루틴 스케줄링 → 작업 실행 → 종료

package main

import (
	"fmt"
	"runtime"
	"sync"
	"sync/atomic"
)

func main() {
	// ============================================
	// 💡 원자성(Atomicity)이란?
	// ============================================
	// 정의: 기능적으로 분할 불가능한 완전히 보증된 일련의 조작
	//
	// 특징:
	// 1. All or Nothing: 모두 성공하거나, 모두 실패
	// 2. Indivisible: 중간 상태가 존재하지 않음
	// 3. Thread-Safe: 다른 프로세스/고루틴의 개입 불가
	//
	// 비유:
	// 원자(Atom) = 더 이상 쪼갤 수 없는 물질의 최소 단위
	// 원자적 연산 = 더 이상 쪼갤 수 없는 프로그램의 최소 연산 단위
	//
	// 필요성:
	// CPU는 "cnt += 1"을 내부적으로 3단계로 수행:
	//   1. LOAD:  메모리에서 cnt 값을 CPU 레지스터로 읽기
	//   2. ADD:   레지스터 값에 1 더하기
	//   3. STORE: 결과를 다시 메모리에 쓰기
	//
	// 문제 상황:
	//   고루틴A: LOAD(100) → ADD(101) → [중단] → STORE(101)
	//   고루틴B:              LOAD(100) → ADD(101) → STORE(101)
	//   결과: 두 번 증가했는데 최종값은 101 (한 번만 증가!)
	//
	// sync/atomic 패키지:
	// - CPU의 원자적 명령어(LOCK XADD, CAS 등)를 Go에서 사용
	// - 하드웨어 레벨에서 원자성 보장
	// - 공식 문서: https://golang.org/pkg/sync/atomic
	//
	// 주요 함수들:
	// - AddInt32, AddInt64, AddUint32, AddUint64: 원자적 덧셈
	// - LoadInt32, LoadInt64: 원자적 읽기
	// - StoreInt32, StoreInt64: 원자적 쓰기
	// - CompareAndSwapInt32, CompareAndSwapInt64: CAS 연산
	// - SwapInt32, SwapInt64: 원자적 교환

	// ============================================
	// ⚙️ 시스템 설정: 멀티코어 활용
	// ============================================
	runtime.GOMAXPROCS(runtime.NumCPU())
	//
	// GOMAXPROCS의 역할:
	// - Go 런타임이 사용할 OS 스레드(P: Processor) 개수 설정
	// - NumCPU(): 시스템의 논리적 CPU 코어 수 반환
	//   예: MacBook M1 Pro 8코어 → 8 반환
	//
	// 왜 설정하는가?
	// 1. 진짜 병렬 실행 활성화
	//    - 기본값도 NumCPU()이지만 명시적으로 설정
	//    - 여러 코어에서 동시에 고루틴 실행
	//
	// 2. 데이터 레이스 가시성 향상
	//    - 싱글 코어: 순차 실행되어 문제가 드러나지 않을 수 있음
	//    - 멀티 코어: 진짜 동시 실행으로 레이스 조건 명확히 발생
	//
	// 내부 동작:
	// Go 스케줄러의 MPG 모델
	// - M (Machine): OS 스레드 (GOMAXPROCS로 제한)
	// - P (Processor): 논리적 프로세서, 고루틴 실행 컨텍스트
	// - G (Goroutine): 실제 고루틴
	//
	// 설정 효과:
	// GOMAXPROCS(1) → 한 번에 하나의 고루틴만 실행 (순차적)
	// GOMAXPROCS(8) → 최대 8개 고루틴 동시 실행 (병렬)

	// ============================================
	// 🔢 공유 변수 선언
	// ============================================
	var cnt int64 = 0
	//
	// 타입 선택: int64
	// - atomic 함수는 특정 타입만 지원:
	//   int32, int64, uint32, uint64, uintptr, Pointer
	// - int는 플랫폼마다 크기가 다름 (32bit or 64bit)
	//   → 명시적으로 int64 사용 (크로스 플랫폼 안전성)
	//
	// 변수의 역할:
	// - 여러 고루틴이 동시에 접근하는 "공유 변수"
	// - 동기화 없이 접근하면 데이터 레이스 발생
	//
	// 메모리 위치:
	// - 힙(Heap)에 할당 (여러 고루틴이 접근 가능하도록)
	// - 주소: &cnt를 통해 atomic 함수에 전달
	//
	// 초깃값: 0
	// - 5000번 증가, 2000번 감소 → 예상 최종값: 3000

	wg := new(sync.WaitGroup)
	//
	// WaitGroup 역할:
	// - 모든 고루틴이 작업을 완료할 때까지 메인 함수 대기
	// - Add(): 대기할 고루틴 개수 추가
	// - Done(): 고루틴 완료 신호 (내부적으로 Add(-1))
	// - Wait(): 카운터가 0이 될 때까지 블로킹
	//
	// new vs var 선언:
	// new(sync.WaitGroup) → 힙에 할당, 포인터 반환
	// var wg sync.WaitGroup → 스택에 할당, 값 타입
	//
	// 둘 다 가능하지만 new() 사용 시 주의:
	// - 함수 인자로 전달 시 포인터로 전달 필수
	// - 복사하면 내부 카운터도 복사되어 의미 없음

	// ============================================
	// 🔼 시나리오 1: 5000번 증가 작업
	// ============================================
	for i := 0; i < 5000; i++ {
		// ────────────────────────────────────
		// 📋 고루틴 시작 전 준비
		// ────────────────────────────────────
		wg.Add(1)
		//
		// 타이밍이 중요!
		// ✅ 올바른 순서: wg.Add(1) → go func()
		// ❌ 잘못된 순서: go func() 안에서 wg.Add(1)
		//
		// 이유:
		// - 고루틴 생성은 비동기적으로 실행됨
		// - 메인 고루틴이 wg.Wait()를 먼저 호출할 수 있음
		// - 카운터가 0이면 Wait()가 즉시 반환 (고루틴 시작 전!)
		//
		// 레이스 컨디션 예:
		// 메인: wg.Wait() (카운터 0, 즉시 반환)
		// 고루틴: wg.Add(1) (너무 늦음!)

		// ────────────────────────────────────
		// 🚀 고루틴 생성 및 실행
		// ────────────────────────────────────
		go func(n int) {
			// 익명 함수 + 고루틴
			// - 클로저(Closure) 주의: 외부 변수 캡처 문제
			// - 파라미터로 전달 (n int): i의 현재 값 복사
			//
			// ❌ 잘못된 예 (클로저 문제):
			// go func() {
			//     fmt.Println(i)  // 모든 고루틴이 같은 i 참조
			// }()
			//
			// ✅ 올바른 예 (값 복사):
			// go func(n int) {
			//     fmt.Println(n)  // 각 고루틴이 독립적인 n 보유
			// }(i)

			// ────────────────────────────────────
			// ⚛️ 원자적 증가 연산
			// ────────────────────────────────────
			// ❌ 비원자적 연산 (데이터 레이스 발생!)
			// cnt += 1
			//
			// 이 한 줄이 CPU에서는:
			// 1. MOV rax, [cnt]     ; cnt를 레지스터로 LOAD
			// 2. ADD rax, 1         ; 레지스터에 ADD
			// 3. MOV [cnt], rax     ; 레지스터를 cnt에 STORE
			//
			// 문제 시나리오 (타임라인):
			// 시간  고루틴A              고루틴B
			// T1    LOAD cnt=100
			// T2    ADD  → 101           LOAD cnt=100  ⚠️
			// T3    STORE cnt=101        ADD  → 101
			// T4                         STORE cnt=101 ⚠️
			//
			// 결과: 두 번 증가했지만 최종값 101 (Lost Update!)

			// ✅ 원자적 연산 (안전!)
			atomic.AddInt64(&cnt, 1)
			//
			// 함수 시그니처:
			// func AddInt64(addr *int64, delta int64) int64
			//
			// 파라미터:
			// - addr: 변수의 메모리 주소 (&cnt)
			//   → 포인터를 받아 직접 메모리 수정
			// - delta: 더할 값 (1)
			//   → 양수: 증가, 음수: 감소
			//
			// 반환값:
			// - 연산 후의 새로운 값 (사용 안 해도 됨)
			//
			// 내부 동작 (x86-64 CPU):
			// LOCK XADD [cnt], 1
			//  ↑
			//  LOCK 접두사의 마법!
			//
			// LOCK의 역할:
			// 1. 메모리 버스(Memory Bus)를 잠금
			// 2. 다른 CPU 코어가 해당 메모리에 접근 차단
			// 3. 연산 완료 후 자동으로 잠금 해제
			// 4. 하드웨어 레벨에서 원자성 보장
			//
			// 성능:
			// - Mutex보다 4~5배 빠름 (락 오버헤드 없음)
			// - 나노초 단위 실행 (~8ns)
			// - CPU 캐시 활용 (L1/L2/L3 캐시)
			//
			// 메모리 순서(Memory Ordering):
			// - atomic 연산은 메모리 배리어(Memory Barrier) 포함
			// - 연산 전/후의 명령어 재배치 방지
			// - 멀티코어에서 일관된 메모리 뷰 보장

			// ────────────────────────────────────
			// ✅ 작업 완료 신호
			// ────────────────────────────────────
			wg.Done()
			//
			// 동등한 코드:
			// wg.Add(-1)
			//
			// 동작:
			// - WaitGroup의 내부 카운터를 1 감소
			// - 카운터가 0이 되면 Wait()를 깨움
			//
			// 주의사항:
			// 1. Done() 호출 횟수 = Add() 호출 횟수
			// 2. Done()을 빠뜨리면 데드락 발생
			// 3. panic 발생 시에도 Done() 호출 보장 필요
			//
			// Best Practice: defer 사용
			// go func() {
			//     defer wg.Done()  // 함수 종료 시 자동 호출
			//     // 작업 수행
			// }()
			//
			// defer의 장점:
			// - panic 발생해도 실행 보장
			// - 코드 가독성 향상
			// - Done() 누락 방지

		}(i) // 즉시 실행, i를 n으로 전달
		//
		// 실행 순서:
		// 1. 익명 함수 정의
		// 2. i를 n으로 복사
		// 3. go 키워드로 고루틴 생성
		// 4. Go 스케줄러가 적절한 시점에 실행
		//
		// 고루틴 생성 비용:
		// - 초기 스택: 2KB (필요 시 자동 증가)
		// - 생성 시간: 마이크로초 단위
		// - OS 스레드보다 1000배 가벼움
		//
		// 스케줄링:
		// - Go 런타임의 M:N 스케줄러
		// - M개의 고루틴을 N개의 OS 스레드에 매핑
		// - 선점형(Preemptive) 스케줄링
		// - 협력적(Cooperative) 양보
	}
	//
	// 루프 종료 시점:
	// - 5000개의 고루틴 생성 완료
	// - 하지만 실행은 아직 진행 중 (비동기!)
	// - WaitGroup 카운터: 5000

	// ============================================
	// 🔽 시나리오 2: 2000번 감소 작업
	// ============================================
	for i := 0; i < 2000; i++ {
		wg.Add(1)
		go func(n int) {
			// ────────────────────────────────────
			// ⚛️ 원자적 감소 연산
			// ────────────────────────────────────
			// ❌ 비원자적 연산
			// cnt -= 1
			//
			// 동일한 데이터 레이스 문제 발생
			// 감소도 LOAD-SUB-STORE 3단계

			// ✅ 원자적 연산
			atomic.AddInt64(&cnt, -1)
			//
			// 트릭: 음수를 더해서 감소 효과
			// - AddInt64는 덧셈만 지원
			// - 하지만 음수 delta 허용
			// - -1을 더하면 결과적으로 1 감소
			//
			// 다른 방법은 없나?
			// - Go 1.19 이전: AddInt64(&cnt, -1)만 가능
			// - Go 1.19+: atomic.Int64 타입 추가
			//   var cnt atomic.Int64
			//   cnt.Add(-1)  // 더 간결
			//
			// 성능은 동일:
			// - 컴파일러가 동일한 CPU 명령어로 변환
			// - LOCK XADD [cnt], -1

			wg.Done()
		}(i)
	}
	//
	// 전체 고루틴 상태:
	// - 증가 고루틴: 5000개 (일부는 완료, 일부는 실행 중)
	// - 감소 고루틴: 2000개 (막 시작)
	// - WaitGroup 카운터: 7000
	//
	// 실행 순서:
	// - 증가/감소 고루틴이 무작위 순서로 실행
	// - Go 스케줄러가 공정하게 분배
	// - 어느 고루틴이 먼저 실행될지 예측 불가

	// ============================================
	// ⏰ 모든 고루틴 완료 대기
	// ============================================
	// Add(7000) == Done(7000) 횟수 같아야 함
	wg.Wait()
	//
	// Wait()의 동작:
	// 1. 내부 카운터 확인
	// 2. 카운터 > 0: 고루틴을 세마포어에서 대기 (블로킹)
	// 3. 카운터 = 0: 즉시 반환
	//
	// 블로킹 메커니즘:
	// - Go 스케줄러에게 제어권 양보
	// - CPU를 점유하지 않음 (busy-wait 아님)
	// - Done() 호출 시 깨어남 확인
	//
	// 내부 구현 (의사 코드):
	// func (wg *WaitGroup) Wait() {
	//     for {
	//         count := atomic.LoadInt32(&wg.counter)
	//         if count == 0 {
	//             return  // 모두 완료
	//         }
	//         // 세마포어에서 대기
	//         runtime_Semacquire(&wg.sema)
	//     }
	// }
	//
	// Add/Done 불일치 시:
	// - Add > Done: 데드락 (영원히 대기)
	//   fatal error: all goroutines are asleep - deadlock!
	//
	// - Add < Done: 패닉 (음수 카운터)
	//   panic: sync: negative WaitGroup counter
	//
	// 디버깅 팁:
	// 1. Add 호출 횟수를 로그로 출력
	// 2. Done 호출 시 defer 사용 (누락 방지)
	// 3. race detector 사용: go run -race main.go

	// ============================================
	// 📊 결과 읽기: 원자적 Load
	// ============================================
	finalCnt := atomic.LoadInt64(&cnt)
	//
	// 함수 시그니처:
	// func LoadInt64(addr *int64) int64
	//
	// 왜 필요한가?
	// 일반 읽기도 위험할 수 있음!
	//
	// 1. 멀티워드 읽기 문제 (32비트 시스템):
	//    var cnt int64  // 64비트
	//
	//    32비트 시스템에서 int64 읽기:
	//    - 상위 32비트 읽기
	//    - [중단] ← 다른 고루틴이 값 변경!
	//    - 하위 32비트 읽기
	//    결과: 절반은 옛값, 절반은 새값 (깨진 값!)
	//
	// 2. CPU 캐시 불일치:
	//    CPU 코어1: cnt = 100 (L1 캐시)
	//    CPU 코어2: cnt = 200 (L1 캐시)
	//
	//    일반 읽기:
	//    - 로컬 캐시에서 읽음
	//    - 다른 코어의 변경사항 못 봄
	//
	//    atomic.LoadInt64:
	//    - 메모리 배리어 적용
	//    - 모든 코어의 캐시 동기화
	//    - 최신 값 보장
	//
	// 3. 컴파일러 최적화 방지:
	//    컴파일러가 변수 읽기를 레지스터로 캐싱할 수 있음
	//
	//    일반 읽기:
	//    - 최적화로 오래된 값 사용 가능
	//
	//    atomic.LoadInt64:
	//    - 컴파일러에게 "최적화 금지" 지시
	//    - 항상 메모리에서 읽기
	//
	// 내부 동작 (x86-64):
	// MOV rax, [cnt]
	// MFENCE  ← 메모리 배리어
	//
	// MFENCE의 역할:
	// - Load/Store 명령어의 순서 보장
	// - CPU 캐시 무효화 (Invalidate)
	// - 메모리 일관성(Coherence) 유지
	//
	// 성능:
	// - 일반 읽기와 거의 동일 (~1ns 차이)
	// - 안전성을 위한 작은 비용

	// ============================================
	// 🖨️ 결과 출력: 2가지 방법 비교
	// ============================================

	// ────────────────────────────────────
	// 방법 1: 직접 읽기 (비권장 ⚠️)
	// ────────────────────────────────────
	fmt.Println("WaitGroup End! Cnt? >>>>> ", cnt)
	//
	// 문제점:
	// 1. 원자적이지 않은 읽기
	//    - 64비트 시스템에서는 대부분 안전
	//    - 하지만 명세상 보장 없음
	//    - 크로스 플랫폼 코드에서 위험
	//
	// 2. 컴파일러 최적화
	//    - 컴파일러가 cnt를 캐싱할 수 있음
	//    - 최신 값이 아닐 수 있음
	//
	// 3. 메모리 가시성 문제
	//    - CPU 캐시 불일치 가능
	//    - 다른 코어의 변경사항 반영 안 될 수 있음
	//
	// 언제 안전한가?
	// - 모든 고루틴이 종료된 후 (wg.Wait() 이후)
	// - 더 이상 쓰기가 없음
	// - 하지만 여전히 권장하지 않음

	// ────────────────────────────────────
	// 방법 2: 원자적 읽기 (권장 ✅)
	// ────────────────────────────────────
	fmt.Println("WaitGroup End! Cnt? >>>>> ", finalCnt)
	//
	// 장점:
	// 1. 원자성 보장
	//    - 하드웨어 레벨에서 안전
	//    - 32/64비트 모두 안전
	//
	// 2. 메모리 가시성
	//    - 메모리 배리어 적용
	//    - 모든 코어에서 일관된 값
	//
	// 3. 컴파일러 최적화 방지
	//    - volatile 읽기와 유사
	//    - 항상 최신 값
	//
	// 4. 코드 명확성
	//    - 의도가 명확함 (원자적 읽기)
	//    - 유지보수 용이
	//
	// Best Practice:
	// - atomic으로 쓴 변수는 atomic으로 읽기
	// - 일관성 유지 (Write atomic, Read atomic)
	// - 혼용 금지 (일부는 atomic, 일부는 일반)

	// ============================================
	// 📈 예상 결과
	// ============================================
	// 증가: +5000
	// 감소: -2000
	// 최종: 3000
	//
	// atomic 사용 시:
	// - 항상 정확히 3000 출력 ✅
	// - 몇 번을 실행해도 동일
	// - 데이터 무결성 보장
	//
	// atomic 미사용 시 (주석 해제):
	// - 2995, 3001, 2998, 3003... 무작위 ❌
	// - 실행마다 다른 결과
	// - 데이터 레이스 발생
	//
	// 검증 방법:
	// 1. atomic 주석 처리
	// 2. go run -race main.go 실행
	// 3. 데이터 레이스 감지 메시지 확인:
	//    WARNING: DATA RACE
	//    Write at 0x... by goroutine X
	//    Previous write at 0x... by goroutine Y
}

// ============================================
// 🎓 핵심 개념 정리
// ============================================
//
// 1. 원자성 (Atomicity)
//    - 더 이상 쪼갤 수 없는 연산
//    - All-or-Nothing
//    - 중간 상태 없음
//
// 2. 데이터 레이스 (Data Race)
//    - 두 개 이상의 고루틴이 동시에 같은 메모리에 접근
//    - 최소 하나는 쓰기 연산
//    - 동기화 없음
//    결과: 예측 불가능한 동작
//
// 3. 동기화 계층
//    하드웨어 (CPU 명령어)
//        ↓
//    atomic 패키지
//        ↓
//    Mutex, RWMutex
//        ↓
//    WaitGroup, Cond
//        ↓
//    채널, 고수준 패턴
//
// 4. 성능 비교
//    atomic < Mutex < 채널
//    빠름              느림
//
//    하지만 용도가 다름!
//    - atomic: 단일 변수 연산
//    - Mutex: 코드 블록 보호
//    - 채널: 통신 기반 동기화
//
// 5. Best Practices
//    ✅ atomic으로 쓴 변수는 atomic으로 읽기
//    ✅ 단순한 카운터는 atomic 사용
//    ✅ 복잡한 자료구조는 Mutex 사용
//    ✅ 가능하면 채널로 통신
//    ✅ race detector 항상 사용
//
// 6. 주의사항
//    ⚠️ atomic 변수를 복사하지 말 것
//    ⚠️ atomic과 일반 연산 혼용 금지
//    ⚠️ 포인터 정렬 주의 (일부 아키텍처)
//    ⚠️ 과도한 atomic 사용 지양 (가독성 저하)
