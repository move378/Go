// 함수 Closure(1)
package main

import "fmt"

func main() {
	/* 클로저(Closure) 익명함수를 변수에 할당할 때! 해당 함수가 외부 스코프의 변수들에 대한
	**참조(Reference)**를 유지하는 메커니즘 값을 단순히 복사하는 것이 아니라, 실제 변수에 대한 동적 연결을 유지한다.
	이를 통해 함수는 외부 변수의 현재 상태에 접근하고 수정할 수 있다.

	핵심 특징: "클로저가 생성될 때의 스코프에 있는 변수들과 생명주기를 공유"
	1) 외부 변수의 값을 복사(스냅샷)하는 것이 아니라, 변수 자체에 대한 참조를 유지
	2) 클로저가 생성된 후 참조된 변수들의 생명주기가 연장됨
	3) 여러 클로저가 같은 변수를 참조하면 상태를 공유함
	4) 함수의 생명주기가 끝난 경우, 즉 반환된 후에도 지역 변수에 접근 가능

	장점: 캡슐화, 상태 유지, 함수 팩토리 패턴
	주의: 메모리 누수 가능성, 예상치 못한 상태 공유

	매개변수 → 복사(Pass by Value)
	클로저 → 참조 유지(Reference Capture)
	클로저 생성 시점 = 익명함수에서 해당 변수를 할당하는 시점
	감싸고 있는 함수와 생명주기 공유는 당연한 이치

	여러가지 사용 이유가 있겠지만, 함수를 호출 할 때 이전에 존재했던 값을 유지하기 위해서 사용.
	[비동기/누적카운트 : 무분별한 전역변수를 남발하는 것을 방지]
	남발하면 객체들이 메모리에 존재하므로, 메모리 부족이나 오버플로우 발생
	클로저를 정확하게 이해하고 사용할 것.

	이 때, 함수는 일급 객체 이므로 변수의 값으로 사용 가능
	일급시민 first class의 개념은
	1) 변수에 할당 가능(Assignment),
	2) 함수의 매개변수로 전달 가능 (Parameter),
	3) 함수의 반환값으로 사용가능 (Return Value),
	4) 런타임에 생성 가능 (Runtime Creation),
	위 네가지가 모두 가능한 함수를 first class citizen
	go에서는 동등성 비교가 제한되어 컴파일 에러가 발생하는 상황, 함수는 go에서 non-comparable 타입
	*/

	//예제1
	multiply := func(x, y int) int { //익명함수를 변수에 할당하는 경우
		return x * y
	}

	r1 := multiply(5, 10)

	fmt.Println("ex1 : ", r1)

	//예제2
	m, n := 10, 5            //변수를 캡처
	sum := func(c int) int { //익명함수 변수 할당
		return m + n + c //지역 변수의 참조를 그대로 가지고 있다. 즉, 지역변수가 소멸되지 않고 참조를 유지함!
	} // 와우! 매개변수로 받지 않아도 변수 m,n을 사용할 수 있구나!
	// 클로져를 사용하면 공통으로 사용하는 m, n 변수를 sum이 호출될 때마다 해당 참조를 사용할 수 있게 됨.

	r2 := sum(10)

	fmt.Println("ex2 : ", r2)

}
