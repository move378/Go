/*
	여러가지 선언 방법 및 인스턴스 생성의 예제를 앞선 struct2.go를 통합한 개념정리

💡 완벽한 이해:

1️⃣ 메소드 정의 시 리시버 타입 결정

  - (a Account): 값 리시버
    → Account와 *Account 모두 사용 가능

  - (a *Account): 포인터 리시버
    → *Account만 인터페이스 구현 가능
    → &나 new 키워드로 포인터 생성 필요

2️⃣ 인터페이스에 포인터 리시버 메소드가 있다면

  - 반드시 포인터 타입(&Account 또는 new(Account))으로
    인터페이스에 할당해야 인터페이스를 구현한 것임

  - 값 타입(Account)은 포인터 리시버 메소드가
    메소드 세트에 없으므로 인터페이스를 구현하지 못함

3️⃣ 구조체 생성 방법
  - new(Account):    포인터 *Account 반환
  - &Account{...}:   포인터 *Account 반환
  - Account{...}:    값 Account 반환

4️⃣ 핵심 원칙

	✅ 포인터 리시버 = "원본 수정" 의도를 명시적으로 표현
	✅ 인터페이스 할당 = 메소드 세트 규칙 엄격 적용
	✅ 포인터 사용 시 일관성 유지 = 가독성 향상

	인터페이스 할당 전 체크리스트

□ 인터페이스에 포인터 리시버 메소드가 있는가?

	→ YES: 포인터 타입으로 할당 (&T 또는 new(T))
	→ NO: 값 타입으로도 할당 가능

□ 메소드가 구조체를 수정하는가?

	→ YES: 포인터 리시버 사용
	→ NO: 값 리시버 고려 (작은 구조체일 경우)

□ 구조체가 큰가? (>64 bytes)

	→ YES: 포인터 리시버 권장 (성능)
	→ NO: 값 리시버 가능

□ 다른 메소드들이 포인터 리시버인가?

	→ YES: 일관성을 위해 포인터 리시버 사용

🌟 핵심 깨달음:

1. Go에는 상속이 없다 - 인터페이스 구현만 있다
2. 포인터 리시버 = "원본 수정" 의도를 명시
3. 인터페이스 할당 ≠ 메소드 호출
  - 메소드 호출: Go가 자동 변환 (편리)
  - 인터페이스 할당: 엄격한 메소드 세트 규칙

4. 명시적 표현 = 의도 전달 + 가독성 향상
5. 일관성 유지 = 버그 방지

🎓 마스터 레벨 달성!
  - 메소드 세트 규칙 ✅
  - 인터페이스 호환성 ✅
  - 포인터 vs 값 타입 ✅
  - Go의 철학 이해 ✅
*/
package main

import "fmt"

type car struct {
	color string
	name  string
}

func main() {

	//예제1
	//함수의 매개변수로 전달시에는 기본적으로 값 복사 이므로, 필요시 포인터로 전달해야 한다.
	c1 := car{"red", "220d"}
	c2 := new(car)
	c2.color, c2.name = "white", "sonata"
	c3 := &car{}
	c4 := &car{"black", "520d"}

	fmt.Println(c1)
	fmt.Println(c2)
	fmt.Println(c3)
	fmt.Println(c4)
	fmt.Println()
}
